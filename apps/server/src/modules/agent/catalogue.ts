import { z } from 'zod';
import { offeredToMcp } from './registry';
import type { AnyTool } from './types';

/**
 * The tool catalogue for the user guide (task 12.14), generated from the registry so the document
 * can never disagree with the tools: `npm run docs:tools` writes it between the markers of
 * `docs/guide/agent-tools.md`, and a test fails if the committed text is out of date.
 */

export const CATALOGUE_START = '<!-- tools:start (generated by npm run docs:tools) -->';
export const CATALOGUE_END = '<!-- tools:end -->';

const CATEGORY_TITLES: Record<AnyTool['category'], string> = {
  knowledge: 'Notes',
  concepts: 'Concepts and the graph',
  sources: 'Sources',
  learning: 'Course and learning',
  files: 'Files',
};

const RISK_TEXT = {
  read: 'Reads',
  write: 'Changes (logged, undoable)',
  destructive: 'Deletes or merges (always asks)',
} as const;

const cell = (text: string) => text.replace(/\|/gu, '\\|').replace(/\s+/gu, ' ').trim();

function inputs(tool: AnyTool): string {
  const schema = z.toJSONSchema(tool.input, { io: 'input', unrepresentable: 'any' }) as {
    properties?: Record<string, unknown>;
    required?: string[];
  };
  const names = Object.keys(schema.properties ?? {});
  if (names.length === 0) return 'none';
  const required = new Set(schema.required ?? []);
  return names.map((name) => `\`${name}\`${required.has(name) ? '' : '?'}`).join(', ');
}

export function toolCatalogue(tools: readonly AnyTool[]): string {
  const sections = (Object.keys(CATEGORY_TITLES) as AnyTool['category'][]).flatMap((category) => {
    const members = tools.filter((tool) => tool.category === category);
    if (members.length === 0) return [];
    return [
      `### ${CATEGORY_TITLES[category]}`,
      '',
      '| Tool | What it does | Inputs (`?` optional) | Risk | MCP |',
      '|---|---|---|---|---|',
      ...members.map(
        (tool) =>
          `| \`${tool.name}\` | ${cell(tool.description)} | ${inputs(tool)} | ${tool.permanent ? 'Records permanently (always asks)' : RISK_TEXT[tool.risk]} | ${offeredToMcp(tool) ? 'yes' : 'no'} |`,
      ),
      '',
    ];
  });
  return [CATALOGUE_START, '', ...sections, CATALOGUE_END].join('\n');
}

/** The text of a document with its generated catalogue replaced. */
export function withCatalogue(document: string, tools: readonly AnyTool[]): string {
  const start = document.indexOf(CATALOGUE_START);
  const end = document.indexOf(CATALOGUE_END);
  if (start < 0 || end < start) throw new Error('The document has no catalogue markers.');
  return `${document.slice(0, start)}${toolCatalogue(tools)}${document.slice(end + CATALOGUE_END.length)}`;
}
